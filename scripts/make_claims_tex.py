#!/usr/bin/env python3
"""Write paper/claims.tex (one \\newcommand per claim) from claims.json.  scripts/verify.py fails if the
committed paper/claims.tex differs from what this script produces."""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def group(v, sep):
    if v.isdigit() and len(v) >= 5:                      # 10888 -> 10{,}888
        head = len(v) % 3 or 3
        return sep.join([v[:head]] + [v[i:i + 3] for i in range(head, len(v), 3)])
    return v


def render():
    c = json.loads((ROOT / 'claims.json').read_text())
    lines = ['% Generated by scripts/make_claims_tex.py from claims.json -- do not edit by hand.']
    for k, v in c.items():
        if k.startswith('_') or not isinstance(v, str):
            continue
        lines.append(r'\newcommand{\cl%s}{%s}' % (k, group(v, '{,}')))
    for r in c['n26']:
        z0 = int(r['z0'])
        cells = ['$(%d,%d)$' % (z0, 13 - z0)] + [group(r[k], r'\,') for k in ('nodes', 'pairs', 'cpu', 'nodesTwo', 'cpuTwo', 'sets', 'cubes', 'cpuCert')]
        lines.append(r'\newcommand{\clrowZ%s}{%s\\}' % ('abcdefg'[z0], ' & '.join(cells)))
    for r in c['n28']:
        z0 = int(r['z0'])
        cells = ['$(%d,%d)$' % (z0, 14 - z0)] + [group(r[k], r'\,') for k in ('nodes', 'pairs', 'cpu', 'cubes', 'cpuCert', 'cpuSat')]
        lines.append(r'\newcommand{\clrowY%s}{%s\\}' % ('abcdefgh'[z0], ' & '.join(cells)))
    for r in c['validation']:
        lines.append(r'\newcommand{\clval%s}{%s}' % (r['key'], r['classes']))
    for r in c['validationRec'] + c['gplus']:
        lines.append(r'\newcommand{\clpairs%s%s}{%s}' % ('gp' if 'g' in r else 'rec', ['', '', '', '', '', '', '', '', 'Eight', '', '', '', '', '', 'Fourteen', '', 'Sixteen', '', '', '', 'Twenty', '', 'TwentyTwo', '', 'TwentyFour'][int(r['n'])], group(r['pairs'], '{,}')))
    for r in c['gplus']:
        lines.append(r'\newcommand{\clgp%s}{%s}' % (['', '', '', '', '', '', '', '', 'Eight', '', '', '', '', '', 'Fourteen', '', 'Sixteen'][int(r['n'])], group(r['classes'], '{,}')))
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    out = ROOT / 'paper' / 'claims.tex'
    if len(sys.argv) > 1 and sys.argv[1] == '--check':
        ok = out.exists() and out.read_text() == render()
        print('claims.tex in sync with claims.json:', ok)
        sys.exit(0 if ok else 1)
    out.parent.mkdir(exist_ok=True)
    out.write_text(render())
    print('wrote', out.relative_to(ROOT))
